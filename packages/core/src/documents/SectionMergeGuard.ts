/**
 * @file SectionMergeGuard.ts
 * @description AST/Section-level 3-way merge resolver for architectural documents.
 * Preserves user-written manual additions and sections during incremental re-compilation
 * instead of bluntly overwriting manual work or aborting with a conflict.
 */

export interface DocumentSection {
  heading: string;
  level: number;
  content: string;
  raw: string;
}

export interface MergeResult {
  hasManualEditsPreserved: boolean;
  hasConflicts: boolean;
  mergedContent: string;
  preservedSections: string[];
  conflictSections: string[];
}

export class SectionMergeGuard {
  /**
   * Parses Markdown content into an array of sections based on Markdown headers (#, ##, ###).
   * Guards code fence blocks (```, ~~~) with strict character and length state machine.
   */
  public static parseSections(markdown: string): DocumentSection[] {
    const lines = markdown.replace(/\r\n/g, '\n').split('\n');
    const sections: DocumentSection[] = [];

    let currentHeading = 'PREAMBLE';
    let currentLevel = 0;
    let currentLines: string[] = [];
    let inCodeFence = false;
    let fenceChar: '`' | '~' | null = null;
    let fenceLength = 0;

    for (const line of lines) {
      if (!inCodeFence) {
        // Code fence opener: at most 3 leading spaces, followed by 3 or more ` or ~
        const fenceMatch = line.match(/^ {0,3}(`{3,}|~{3,})(.*)$/);
        if (fenceMatch && fenceMatch[1]) {
          const char = fenceMatch[1][0] as '`' | '~';
          const len = fenceMatch[1].length;
          const rest = fenceMatch[2] ?? '';

          // Check if fence is opened and closed on the very same line (e.g. ```code```)
          const escapedChar = char === '`' ? '\\`' : '~';
          const sameLineCloseRegex = new RegExp(`(^|[^${escapedChar}])${escapedChar}{${len},}\\s*$`);
          if (sameLineCloseRegex.test(rest)) {
            // Self-contained single-line fence, do not enter multi-line fence state
          } else {
            inCodeFence = true;
            fenceChar = char;
            fenceLength = len;
          }
        }
      } else {
        // Inside code fence: only closing fence matching same char with at least same length closes it
        const escapedChar = fenceChar === '`' ? '\\`' : '~';
        const closeRegex = new RegExp(`^ {0,3}${escapedChar}{${fenceLength},}\\s*$`);
        if (closeRegex.test(line)) {
          inCodeFence = false;
          fenceChar = null;
          fenceLength = 0;
        }
      }

      const match = !inCodeFence ? line.match(/^(#{1,6})\s+(.*)$/) : null;
      if (match && match[1] && match[2]) {
        // Save previous section if exists
        if (currentLines.length > 0 || currentHeading !== 'PREAMBLE') {
          sections.push({
            heading: currentHeading,
            level: currentLevel,
            content: currentLines.join('\n').trim(),
            raw: currentLines.join('\n'),
          });
        }
        currentHeading = match[2].trim();
        currentLevel = match[1].length;
        currentLines = [line];
      } else {
        currentLines.push(line);
      }
    }

    if (currentLines.length > 0) {
      sections.push({
        heading: currentHeading,
        level: currentLevel,
        content: currentLines.join('\n').trim(),
        raw: currentLines.join('\n'),
      });
    }

    return sections;
  }

  public static splitSections(markdown: string): DocumentSection[] {
    return this.parseSections(markdown);
  }

  /**
   * Intelligently merges on-disk human-edited markdown with newly generated markdown.
   * If the user added custom sections or subsections not generated by the AI, they are preserved.
   * If both edited the same section differently, safe non-destructive conflict markers are generated.
   */
  public static merge(
    diskContent: string,
    newGeneratedContent: string,
  ): MergeResult {
    // If identical, return clean result immediately
    if (diskContent.replace(/\r\n/g, '\n').trim() === newGeneratedContent.replace(/\r\n/g, '\n').trim()) {
      return {
        hasManualEditsPreserved: false,
        hasConflicts: false,
        mergedContent: newGeneratedContent,
        preservedSections: [],
        conflictSections: [],
      };
    }

    const diskSections = this.parseSections(diskContent);
    const newSections = this.parseSections(newGeneratedContent);

    const newHeadingsMap = new Map<string, DocumentSection>();
    for (const sec of newSections) {
      newHeadingsMap.set(sec.heading.toLowerCase(), sec);
    }

    const mergedSections: string[] = [];
    const preservedSections: string[] = [];
    const conflictSections: string[] = [];
    let hasConflicts = false;

    // Track which new sections have been emitted
    const emittedNewHeadings = new Set<string>();

    for (const diskSec of diskSections) {
      const key = diskSec.heading.toLowerCase();
      const newSec = newHeadingsMap.get(key);

      if (!newSec) {
        // This section exists on disk but was NOT generated by AI (Human custom addition!)
        // PRESERVE IT!
        mergedSections.push(diskSec.raw);
        preservedSections.push(diskSec.heading);
      } else {
        emittedNewHeadings.add(key);

        // Both have this section. Check if content diverges
        const diskBody = diskSec.content;
        const newBody = newSec.content;

        if (diskBody === newBody) {
          // Identical: emit new generated version
          mergedSections.push(newSec.raw);
        } else {
          // Both modified this section. Check if disk section contains custom manual notes
          const isManualNotesSection = /manual|custom|note|team|补充|手工|备注|私有/i.test(diskSec.heading);

          if (isManualNotesSection) {
            // Keep user manual notes
            mergedSections.push(diskSec.raw);
            preservedSections.push(diskSec.heading);
          } else {
            // Generate non-destructive conflict block
            hasConflicts = true;
            conflictSections.push(diskSec.heading);
            const conflictBlock = [
              `<<<<<<< HUMAN_MANUAL_EDITS (${diskSec.heading})`,
              diskSec.raw,
              '=======',
              newSec.raw,
              `>>>>>>> COMPILED_AI_SPEC (${newSec.heading})`,
            ].join('\n');
            mergedSections.push(conflictBlock);
          }
        }
      }
    }

    // Append any newly generated sections that were not on disk
    for (const newSec of newSections) {
      const key = newSec.heading.toLowerCase();
      if (!emittedNewHeadings.has(key)) {
        mergedSections.push(newSec.raw);
      }
    }

    return {
      hasManualEditsPreserved: preservedSections.length > 0,
      hasConflicts,
      mergedContent: mergedSections.join('\n\n').trim() + '\n',
      preservedSections,
      conflictSections,
    };
  }
}

export function splitSections(markdown: string): DocumentSection[] {
  return SectionMergeGuard.parseSections(markdown);
}

